function toDoc(
  seed: Omit<QmsDocument, "type" | "sections"> & { how: string[] },
  type: QmsDocument["type"],
): QmsDocument {
  const { how, ...rest } = seed;
  return {
    ...rest,
    type,
    sections: [
      {
        heading: "How to complete this",
        paragraphs: [seed.purpose],
        steps: how,
      },
    ],
  };
}

export const allDocuments: QmsDocument[] = [
  ...documents,
  ...sopSeed.map((s) => toDoc(s, "sop")),
  ...formSeed.map((s) => toDoc(s, "form")),
];

export function getDocument(id: string) {
  return allDocuments.find((d) => d.id === id);
}

export function documentsForStage(stageId: string) {
  return allDocuments.filter((d) => d.stageIds.includes(stageId));
}

export function childrenOf(parentId: string) {
  return allDocuments.filter((d) => d.parentId === parentId);
}
